// Builds tools/citydata.json — the place-name vocabulary tables embedded in the
// page. Run: node tools/build-citydata.mjs
//
// Sources (Apache-2.0, transcribed from public-domain USPS Publication 28):
//   poetic-systems/addresstables cityabbreviations  — the four words USPS says
//     city names actually get abbreviated with (Pub 28 §223): SAINT, SAINTE,
//     MOUNT, FORT.
//   poetic-systems/addresstables streetsuffixes     — Pub 28 Appendix C1: every
//     suffix spelling (HEIGHTS/HTS, MOUNTAIN/MTN, ...) so county records that
//     abbreviate a city word match the record that spells it out.
// No heuristics: matching is vocabulary lookup, and anything the vocabulary
// does not cover becomes a visible flag — the flagging direction is safe.
import { writeFileSync, readFileSync } from "node:fs";

const get = async (url) => {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.text();
};

const cityGo = await get("https://raw.githubusercontent.com/poetic-systems/addresstables/main/cityabbreviations/cityabbreviations.go");
const cityAbbr = [...cityGo.matchAll(/\{Full:\s*"([A-Z]+)",\s*Short:\s*"([A-Z]+)"\}/g)].map((m) => [m[1], m[2]]);
if (cityAbbr.length !== 4) throw new Error(`city abbreviations: expected 4 rows, got ${cityAbbr.length}`);

const ssGo = await get("https://raw.githubusercontent.com/poetic-systems/addresstables/main/streetsuffixes/streetsuffixes.go");
const suffixes = [];
for (const block of ssGo.split(/\{\s*\n\s*Primary:/).slice(1)) {
  const p = block.match(/^\s*"([A-Z ]+)"/);
  const alts = block.match(/Alt:\s*\[\]string\{([\s\S]*?)\}/);
  if (!p || !alts) continue;
  const list = [...alts[1].matchAll(/"([A-Z0-9]+)"/g)].map((m) => m[1]);
  if (list.length) suffixes.push([p[1], [...new Set(list)]]);
}
if (suffixes.length < 150) throw new Error(`suffixes: only ${suffixes.length} rows parsed`);

const data = {
  note: "Generated by tools/build-citydata.mjs from poetic-systems/addresstables (Apache-2.0), transcribed from USPS Publication 28. Do not edit by hand.",
  cityAbbreviations: cityAbbr,
  streetSuffixes: suffixes,
};
writeFileSync(new URL("./citydata.json", import.meta.url), JSON.stringify(data));

/* Embed the table between the CITYDATA markers in the page so the shipped logic needs no fetch. */
const vocab = { cityAbbr: cityAbbr, suffix: suffixes };
const htmlUrl = new URL("../utah-property-tax-estimator.html", import.meta.url);
const html = readFileSync(htmlUrl, "utf8");
const beg = html.indexOf("/* CITYDATA:BEGIN");
const endMark = html.indexOf("/* CITYDATA:END */");
if (beg < 0 || endMark < 0) throw new Error("CITYDATA markers not found in the page");
const block = "/* CITYDATA:BEGIN — generated by tools/build-citydata.mjs from tools/citydata.json; do not edit. */\nvar PLACE_VOCAB = " + JSON.stringify(vocab) + ";\n/* CITYDATA:END */";
writeFileSync(htmlUrl, html.slice(0, beg) + block + html.slice(endMark + "/* CITYDATA:END */".length));
console.log(`tools/citydata.json: ${cityAbbr.length} city abbreviations, ${suffixes.length} suffix rows; embedded into the page`);
